"""
D_G_final.py

Utilities for plotting ensemble diffusion/growth curves and histograms
from nested model-wrapper dictionaries.

This module provides a single SRPlotter class focused on plotting:
    - plot_eval_D_multi_std
    - plot_eval_G_multi_std
    - plot_eval_hist_multi
    - plot_eval_hist_multi_separate_stacked
    - plot_eval_hist_multi_separate_stacked_range

Important update
----------------
`plot_eval_hist_multi_separate_stacked_range` now uses paired
(time, density) samples from each wrapper via:

    _get_wrapper_time(wrapper)     -> array of times
    _get_wrapper_density(wrapper)  -> array of densities

This means the early/late decomposition is done at the sample level,
not at the wrapper level.

Additional update
-----------------
`plot_eval_D_multi_std` and `plot_eval_G_multi_std` now accept:
    - `hist_labels` for histogram legend entries
    - `sym_labels` for symbolic-regression legend entries

If `hist_labels` is not provided, it defaults to:
    ["Repl. 1", "Repl. 2", ...]

If `sym_labels` is not provided, it defaults to:
    {
        "2_3": r"$D_{1,SR}$",
        "2_5": r"$D_{2,SR}$",
        "3_1": r"$D_{3,SR}$",
    }

`sym_labels` may be supplied as:
    - a mapping keyed by outer group key
    - a sequence, zipped to outer_keys in order
    - a single string, reused for all groups
    - None, in which case the default mapping above is used for matching keys
      and any remaining keys fall back to the autogenerated symbolic label

Styling update
--------------
Axis label font sizes, tick-label font sizes, title font sizes, and
major/minor tick sizes are now exposed explicitly across the plotting API.
"""

